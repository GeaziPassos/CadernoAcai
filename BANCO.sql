CREATE DATABASE IF NOT EXISTS CADERNOACAI;

USE CADERNOACAI;

CREATE TABLE IF NOT EXISTS PESSOA(
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    duplaID INT
);

DELIMITER //
CREATE PROCEDURE inserirPessoa (
    IN p_nome VARCHAR(100)
    IN p_duplaID INT
)
BEGIN 
    INSERT INTO pessoa (nome, duplaID),
    VALUES (p_nome, p_duplaID)
END //